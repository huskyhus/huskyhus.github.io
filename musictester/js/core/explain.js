/** コードの解説。{ title, tones, functionText, lines } */
export function explainChord(chord, key) {
  const c = realize(chord, key);
  const lines = [];
  if (chord.kind === "sec") {
    const targetChord = { kind: "scale", deg: chord.target, size: 3, harmonic: chord.target === 5 };
    const t = realize(targetChord, key);
    lines.push(`${t.name}（${t.roman}）を一時的な主和音とみなしたときの V です。調の外の音を含みますが、${t.name} へ進むと「ここに帰る」という流れがはっきりして、進行に勢いが生まれます。`);
  } else if (chord.kind === "abs") {
    const shape = `${c.semi}:${QUALITIES[c.quality].family}`;
    const inScale = isDiatonic(chord, key) && SCALES[key.mode][chord.letter] === c.semi;
    lines.push(inScale
      ? DEGREE_TEXT[key.mode][chord.letter + 1]
      : BORROWED_TEXT[shape] || "調の外の和音です。進行に色を付けたり、転調のきっかけになったりします。");
  } else {
    if (key.mode === "minor" && chord.harmonic && (chord.deg === 5 || chord.deg === 7)) {
      lines.push(HARMONIC_TEXT[chord.deg]);
    } else {
      lines.push(DEGREE_TEXT[key.mode][chord.deg]);
    }
  }
  if (chord.kind !== "abs" && !isDiatonic(chord, key) && chord.kind !== "sec") {
    lines.push(`${keyName(key)}の音階（${scaleNames(key).join(" ")}）にない音を含みます。`);
  }
  const f = FUNCTION_INFO[c.func];
  return {
    title: `${c.name}（${c.roman}）`,
    tones: c.tones.map(t => t.name),
    func: c.func,
    functionText: `${c.func} = ${f.name}：${f.text}`,
    lines,
  };
}

